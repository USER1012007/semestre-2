public class acuaticas extends protegido {
  int num_lagos;
  double extension_lagos;
  String nombre;
  String especie_protegida;

  public int getNum_lagos() { return num_lagos; }
  public void setNum_lagos(int num_lagos) { this.num_lagos = num_lagos; }
  public double getExtension_lagos() { return extension_lagos; }
  public void setExtension_lagos(double extension_lagos) {
    this.extension_lagos = extension_lagos;
  }
  public String getNombre() { return nombre; }
  public void setNombre(String nombre) { this.nombre = nombre; }
  public String getEspecie_protegida() { return especie_protegida; }
  public void setEspecie_protegida(String especie_protegida) {
    this.especie_protegida = especie_protegida;
  }
}
